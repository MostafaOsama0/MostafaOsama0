import { execSync } from 'node:child_process';
import { readFile, writeFile, readdir, unlink } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const ROOT = process.cwd();
const SOURCE = resolve(ROOT, 'readme.source.md');
const OUTPUT = resolve(ROOT, 'README.md');
const ASSETS = resolve(ROOT, '.github/assets');

// Extract per-block alt text declared via `<!-- aura-alt: ... -->` immediately before each ```aura block.
const sourceText = await readFile(SOURCE, 'utf-8');
const altTexts = [];
const blockRegex = /(?:<!--\s*aura-alt:\s*(.*?)\s*-->\s*\r?\n)?```aura\b[^\r\n]*\r?\n[\s\S]*?```/g;
for (const match of sourceText.matchAll(blockRegex)) {
  altTexts.push(match[1] !== undefined ? match[1].trim() : null);
}

// Clear stale SVG hashes before rebuilding.
try {
  const existing = await readdir(ASSETS);
  await Promise.all(
    existing
      .filter((f) => f.endsWith('.svg'))
      .map((f) => unlink(join(ASSETS, f)))
  );
} catch {
  // Assets directory will be created by readme-aura build.
}

execSync(`npx --yes readme-aura build -s "${SOURCE}" -o "${OUTPUT}" -a "${ASSETS}"`, {
  stdio: 'inherit',
});

let readme = await readFile(OUTPUT, 'utf-8');

// Strip the helper `<!-- aura-alt: ... -->` comments from the generated README.
readme = readme.replace(/<!--\s*aura-alt:.*?-->\r?\n?/g, '');

// Replace generic `![readme-aura-component-N](path "Generated by readme-aura")` with descriptive alt text.
readme = readme.replace(
  /!\[readme-aura-component-(\d+)\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g,
  (full, idxStr, url) => {
    const idx = Number.parseInt(idxStr, 10);
    const alt = altTexts[idx];
    if (alt === null || alt === undefined) {
      return `![Decorative banner](${url})`;
    }
    return `![${alt}](${url})`;
  }
);

// Clean up any leading blank lines or triple newlines left behind by removed comments.
readme = readme.replace(/\n{3,}/g, '\n\n').trimStart();

await writeFile(OUTPUT, readme, 'utf-8');
console.log(`Applied descriptive alt text to ${altTexts.length} aura SVG block(s) in README.md.`);
